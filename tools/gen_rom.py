#!/usr/bin/env python3
"""Tiny, strict two-pass 6502 assembler for pulse.s; produces 256B + iNES."""
import argparse
from pathlib import Path

IMPLIED = {"sei": 0x78, "cld": 0xD8, "txs": 0x9A, "rti": 0x40}
IMMEDIATE = {"lda": 0xA9, "ldx": 0xA2}
ABSOLUTE = {"sta": 0x8D, "jmp": 0x4C}
BASE = 0x8000


def number(token, labels):
    token = token.strip().lower()
    if token.startswith("$"):
        return int(token[1:], 16)
    if token in labels:
        return labels[token]
    return int(token, 0)


def assemble(source):
    labels, statements, pc = {}, [], BASE
    for lineno, line in enumerate(source.splitlines(), 1):
        line = line.split(";", 1)[0].strip().lower()
        if not line:
            continue
        if line.endswith(":"):
            label = line[:-1]
            if label in labels:
                raise ValueError(f"line {lineno}: duplicate label {label}")
            labels[label] = pc
            continue
        parts = line.split(None, 1)
        op, arg = parts[0], parts[1] if len(parts) == 2 else ""
        if op == ".org":
            pc = number(arg, {})
            if not BASE <= pc < BASE + 256:
                raise ValueError(f"line {lineno}: .org outside 256-byte ROM")
            continue
        if op in IMPLIED and not arg:
            size = 1
        elif op in IMMEDIATE and arg.startswith("#"):
            size = 2
        elif op in ABSOLUTE or op == ".word":
            size = 3 if op in ABSOLUTE else 2
        else:
            raise ValueError(f"line {lineno}: unsupported instruction {line}")
        if not BASE <= pc or pc + size > BASE + 256:
            raise ValueError(f"line {lineno}: instruction outside 256-byte ROM")
        statements.append((pc, op, arg, lineno))
        pc += size

    rom, used, listing = bytearray([0xEA] * 256), set(), []
    for pc, op, arg, lineno in statements:
        if op in IMPLIED:
            data = bytes([IMPLIED[op]])
        elif op in IMMEDIATE:
            data = bytes([IMMEDIATE[op], number(arg[1:], labels)])
        else:
            value = number(arg, labels)
            if not 0 <= value <= 0xFFFF:
                raise ValueError(f"line {lineno}: invalid 16-bit operand")
            data = bytes([value & 255, value >> 8])
            if op != ".word":
                data = bytes([ABSOLUTE[op]]) + data
        offsets = set(range(pc - BASE, pc - BASE + len(data)))
        if used & offsets:
            raise ValueError(f"line {lineno}: overlapping ROM content")
        used |= offsets
        rom[pc - BASE:pc - BASE + len(data)] = data
        listing.append(f"{pc:04X}  {data.hex(' ').upper():<9} {op} {arg}")
    for offset, label in ((0xFA, "interrupt"), (0xFC, "reset"), (0xFE, "interrupt")):
        if int.from_bytes(rom[offset:offset + 2], "little") != labels[label]:
            raise ValueError(f"Invalid {label} vector")
    return bytes(rom), "\n".join(listing) + "\n", labels


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[1] / "rom/pulse.s")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    rom, listing, _ = assemble(args.source.read_text())
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "rom256.bin").write_bytes(rom)
    (args.out / "rom.lst").write_text(listing)
    rows = [", ".join(f"0x{b:02x}" for b in rom[i:i + 16]) for i in range(0, 256, 16)]
    header = "// Generated by tools/gen_rom.py; do not edit.\n#pragma once\n#define ROM256_BYTES { \\\n"
    header += ", \\\n".join(rows) + " \\\n}\n"
    (args.out / "rom256.h").write_text(header)
    # Mapper 0, one 16KiB PRG bank and one blank 8KiB CHR bank. Only for
    # emulator smoke tests; physical hardware retains its original CHR chip.
    ines = b"NES\x1a" + bytes([1, 1]) + bytes(10)
    (args.out / "famidi.nes").write_bytes(ines + rom * 64 + bytes(8192))
    print(f"ROM: {len(rom)} bytes; iNES: {len(ines) + 16384 + 8192} bytes")


if __name__ == "__main__":
    main()
